#BUSINESS PROBLEM SOLVING QUESTION

-- --Q1. What is the total revenue generated by male vs. female customers?
SELECT gender, SUM(purchase_amount) as total_revenue
FROM customer_details
GROUP BY gender;

-- --Q2. Which customers used a discount but still spent more than the average purchase amount?
SELECT
	customer_id, 
	purchase_amount
FROM customer_details
WHERE discount_applied = 'Yes' AND
purchase_amount >= (SELECT AVG(purchase_amount) FROM customer_details);


-- -- Q3. Which are the top 5 products with the highest average review rating?
SELECT
	item_purchased,
	ROUND(AVG(review_rating),2) avg_reviewRating
FROM customer_details
GROUP BY 1
ORDER BY AVG(review_rating) DESC
LIMIT 5;

-- --Q4. Compare the average Purchase Amounts between Standard and Express Shipping.
SELECT 
	shipping_type,
    AVG(purchase_amount) AS avg_purchaseAmount
FROM customer_details
WHERE shipping_type IN('Standard', 'Express')
GROUP BY 1;

-- Q5. Do subscribed customers spend more? Compare average spend and total revenue 
SELECT 
	subscription_status,
    COUNT(customer_id) total_orders,
    AVG(purchase_amount) AS avg_purch_Amount,
    SUM(purchase_amount) AS total_Amount
FROM customer_details
GROUP BY 1
ORDER BY 3,4;

-- --Q6. Which 5 products have the highest percentage of purchases with discounts applied?
SELECT	
	item_purchased,
	ROUND (100*SUM(CASE WHEN discount_applied = 'YES' THEN 1 ELSE 0 END) / COUNT(*),2) AS perc_with_discount
FROM customer_details
GROUP BY 1
ORDER BY perc_with_discount DESC
LIMIT 5;

-- -Q7. Segment customers into New, Returning, and Loyal based on their total 
WITH segment_details AS (
SELECT 
	customer_id
	previous_purchases,
    CASE
		WHEN previous_purchases = 1 THEN 'NEW'
        WHEN previous_purchases<=10 THEN 'Returning'
        ELSE 'Loyal'
        END AS customers_segment
FROM customer_details)

SELECT 
	customers_segment,
    COUNT(*) AS total_customers
FROM segment_details
GROUP BY 1
ORDER BY 2 DESC;


-- --Q8. What are the top 3 most purchased products within each category?
WITH rankDetails AS
(SELECT
	category,
    item_purchased,
    COUNT(customer_id) as total_orders,
ROW_NUMBER() OVER(PARTITION BY category ORDER BY COUNT(customer_id) DESC) ranking
FROM customer_details
GROUP BY 1,2)

SELECT
	category,
    item_purchased,
    total_orders,
    ranking
FROM rankDetails
WHERE ranking <=3;

-- --Q9. Are customers who are repeat buyers (more than 5 previous purchases) also likely to subscribe?
SELECT
	subscription_status,
    COUNT(customer_id)
FROM customer_details
WHERE previous_purchases > 5
GROUP BY 1;

-- --Q10. What is the revenue contribution of each age group? 
